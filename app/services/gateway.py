"""Versioned, fail-closed boundary for the application's external AI payloads.

This is schema minimization, not a claim that regex can anonymize documents.
No confidential-document schema exists here: such data is always rejected.
"""
import json
import re
from datetime import date
from typing import Annotated, Literal
from urllib.parse import urlsplit
from pydantic import BaseModel, ConfigDict, Field, ValidationError, create_model
from app.schemas import Locality

VERSION = '1.0'
Number = Annotated[float, Field(strict=True, allow_inf_nan=False, ge=0, le=1e12)]
Metric = Literal['cost', 'clicks', 'impressions', 'conversions', 'contacts', 'qualified',
                 'appointments', 'hires', 'cpc', 'cpq', 'cph', 'ctr', 'days', 'rows']
Alias = Annotated[str, Field(pattern=r'^(all|c[1-9][0-9]*|locality_[1-9][0-9]*|keyword_[1-9][0-9]*)$')]


class Strict(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True)


Metrics = create_model('AggregateMetrics', __base__=Strict,
    **{k: (Number | None, None) for k in Metric.__args__})


class Fact(Strict):
    subject: Alias
    period: Literal['current', 'previous']
    metric: Metric
    value: Number


class Snapshot(Strict):
    scope: Literal['real', 'demo']
    start: str = Field(pattern=r'^\d{4}-\d{2}-\d{2}$')
    end: str = Field(pattern=r'^\d{4}-\d{2}-\d{2}$')
    expected_days: int = Field(ge=1, le=367)
    facts: dict[Annotated[str, Field(pattern=r'^f[1-9][0-9]*$')], Fact] = Field(max_length=2500)
    definitions: str = Field(max_length=800)


class Candidate(Strict):
    id: int = Field(gt=0)
    category: Literal['campanhas', 'qualidade', 'palavras-chave', 'geografia', 'orcamento']
    current: Metrics
    previous: Metrics
    areas: dict[Literal['trabalhista', 'previdenciario'], Metrics]


class Article(Strict):
    id: str = Field(pattern=r'^[a-f0-9]{16}$')
    title: str = Field(max_length=220)
    url: str = Field(max_length=1000)
    source: str = Field(max_length=80)
    source_id: Literal['atos', '012news', 'classelider']
    published: str = Field(pattern=r'^\d{4}-\d{2}-\d{2}$')
    excerpt: str = Field(max_length=1500)
    cities: list[Locality] = Field(min_length=1, max_length=20)
    topics: list[Literal['trabalho', 'previdencia']] = Field(max_length=2)
    basis: str = Field(max_length=150)


class Source(Strict):
    id: Literal['atos', '012news', 'classelider']
    name: str = Field(max_length=80)
    url: str = Field(max_length=1000)
    status: Literal['read', 'partial', 'unavailable']
    complete_window: bool
    items_found: int = Field(ge=0)
    undated_skipped: int = Field(ge=0)
    note: str = Field(default='', max_length=200)


class Signal(Strict):
    topic: Literal['trabalho', 'previdencia']
    label: str = Field(max_length=80)
    count: int = Field(ge=0)
    previous_count: int | None = Field(ge=0)
    source_count: int = Field(ge=0, le=3)
    interpretation: str = Field(max_length=200)


class PublicNews(Strict):
    articles: list[Article] = Field(max_length=40)
    signals: list[Signal] = Field(max_length=2)
    source_checks: list[Source] = Field(max_length=3)
    truncated: bool


def identifier_check(value):
    # Supplemental defense. Confidential free text is not an accepted input type.
    if isinstance(value, str) and re.search(r'\b\d{3}[. ]?\d{3}[. ]?\d{3}[- ]?\d{2}\b|[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}|\b(?:\+55\s*)?\(?\d{2}\)?[ -]?9?\d{4}[ -]?\d{4}\b', value):
        raise ValueError('Identifier rejected')
    if isinstance(value, dict):
        for item in value.values(): identifier_check(item)
    elif isinstance(value, list):
        for item in value: identifier_check(item)


def validate_evidence(value):
    if not isinstance(value, dict): raise ValueError('Unknown payload')
    if 'facts' in value:
        result = Snapshot.model_validate(value)
        if date.fromisoformat(result.end) < date.fromisoformat(result.start): raise ValueError('Period')
        # This text is generated by our server, never supplied by users/models.
        from app.services.insights import DEFINITIONS
        if result.definitions != DEFINITIONS: raise ValueError('Definitions changed')
        return result.model_dump(exclude_unset=True)
    result = PublicNews.model_validate(value)
    from app.integrations.news import SOURCES
    catalog = {s['id']: s for s in SOURCES}
    for item in [*result.articles, *result.source_checks]:
        source_id = item.source_id if isinstance(item, Article) else item.id
        expected = catalog[source_id]
        parsed = urlsplit(item.url)
        if (parsed.scheme != 'https' or parsed.netloc != urlsplit(expected['base']).netloc
                or parsed.username or parsed.password or parsed.query or parsed.fragment):
            raise ValueError('Source URL not approved')
        if isinstance(item, Article):
            date.fromisoformat(item.published)
            if item.source != expected['name']: raise ValueError('Source mismatch')
        elif item.name != expected['name']: raise ValueError('Source mismatch')
    return result.model_dump(exclude_unset=True)


def prepare(content):
    """Return compact approved JSON, or reject before an HTTP client is opened."""
    from app.integrations.openai import AIError
    try:
        if len(content.encode('utf-8')) > 40000: raise ValueError('Size')
        value = json.loads(content)
        if isinstance(value, list):
            if not 1 <= len(value) <= 20: raise ValueError('Candidates')
            approved = [Candidate.model_validate(v).model_dump(exclude_unset=True) for v in value]
        elif isinstance(value, dict) and set(value) == {'evidence', 'analysis'}:
            from app.services.insights import Analysis
            from app.services.news import NewsAnalysis
            evidence = validate_evidence(value['evidence'])
            schema = Analysis if 'facts' in evidence else NewsAnalysis
            approved = {'evidence': evidence, 'analysis': schema.model_validate(value['analysis']).model_dump()}
        else:
            approved = validate_evidence(value)
        identifier_check(approved)
        return json.dumps(approved, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
    except (ValueError, TypeError, KeyError, ValidationError, RecursionError):
        raise AIError('Envio bloqueado: os dados não correspondem ao formato público ou agregado permitido.', 422) from None
